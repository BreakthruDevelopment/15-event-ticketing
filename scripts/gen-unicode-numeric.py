#!/usr/bin/env python3
"""Regenerates src/lib/unicode-numeric.generated.ts: every code point whose Unicode Numeric_Type is not None
(Decimal, Digit or Numeric), read from the Unicode Character Database that ships with Python's `unicodedata`.

JavaScript regexes expose \\p{N} (the general category) but not Numeric_Type, and the two differ: CJK ideographs such as
U+5341 (ten) or U+5344 (twenty) are letters (Lo) with a numeric value. The FAQ checks refuse any numeral they cannot fold
to an ASCII digit, so they need the whole Numeric_Type set, not a hand-written list of the numerals somebody thought of.

Run:  python3 scripts/gen-unicode-numeric.py   (then commit the output; src/lib/unicode-numeric.test.ts checks it)
"""
import unicodedata
from pathlib import Path

ranges = []
for cp in range(0x110000):
    try:
        unicodedata.numeric(chr(cp))
    except (ValueError, TypeError):
        continue
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

flat = ", ".join(f"0x{a:x}, 0x{b:x}" for a, b in ranges)
count = sum(b - a + 1 for a, b in ranges)
out = Path(__file__).resolve().parent.parent / "src/lib/unicode-numeric.generated.ts"
out.write_text(
    "// GENERATED by scripts/gen-unicode-numeric.py: do not edit.\n"
    f"// Unicode {unicodedata.unidata_version}: every code point with Numeric_Type != None ({count} code points).\n"
    "// Flat list of inclusive [first, last] code point pairs, ascending.\n"
    f"export const UNICODE_VERSION = \"{unicodedata.unidata_version}\";\n"
    f"export const NUMERIC_TYPE_RANGES: readonly number[] = [{flat}];\n"
)
print(f"wrote {out} ({len(ranges)} ranges, {count} code points, Unicode {unicodedata.unidata_version})")
